"""Render ``TOOLS.md``: the tool catalog for the committed API spec.

    cd mcp-server && python -m azuregos_mcp.catalog          # rewrite TOOLS.md
    cd mcp-server && python -m azuregos_mcp.catalog --check  # CI: fail if stale

The server builds its tools from the live instance, so this file isn't used
at runtime. It exists so a pull request that changes the API shows, in the
diff, exactly which MCP tools it adds, changes or removes.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from azuregos_mcp.spec import build_toolset

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SPEC = ROOT.parent / "docs" / "openapi.json"
DEFAULT_OUT = ROOT / "TOOLS.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(spec: dict) -> str:
    toolset = build_toolset(spec, strict=True)
    lines = [
        "# Azuregos MCP tools",
        "",
        "<!-- Generated by `python -m azuregos_mcp.catalog` from docs/openapi.json."
        " Don't edit by hand. -->",
        "",
        f"{len(toolset.operations)} tools, one per API operation.",
        "",
        "| Tool | Endpoint | Arguments | Summary |",
        "|---|---|---|---|",
    ]
    for op in sorted(toolset.operations.values(), key=lambda o: (o.tags[:1], o.name)):
        props = op.input_schema["properties"]
        required = set(op.input_schema.get("required", []))
        args = ", ".join(
            f"`{name}`" + ("" if name in required else "?") for name in props
        ) or "none"
        kind = "read-only" if op.read_only else ("destructive" if op.destructive else "writes")
        lines.append(
            f"| `{op.name}` | `{op.method} {op.path}` | {args} "
            f"| {_cell(op.summary)} ({kind}) |"
        )
    lines += [
        "",
        "## Not exposed",
        "",
        "Operations marked `x-azuregos-mcp: {exclude: …}` in the backend:",
        "",
        "| Operation | Why |",
        "|---|---|",
    ]
    for name, why in sorted(toolset.excluded.items()):
        lines.append(f"| `{name}` | {_cell(why)} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render TOOLS.md from the OpenAPI spec.")
    parser.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args(argv)

    current = render(json.loads(args.spec.read_text()))
    if args.check:
        if not args.out.exists() or args.out.read_text() != current:
            print(
                f"{args.out.name} is out of date with {args.spec.name}. "
                "Run: cd mcp-server && python -m azuregos_mcp.catalog",
                file=sys.stderr,
            )
            return 1
        print(f"{args.out.name} is up to date.")
        return 0
    args.out.write_text(current)
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
