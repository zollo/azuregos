#!/usr/bin/env python3
"""Generate the zollo.azuregos Ansible modules from the Azuregos OpenAPI spec.

    python ansible/generator/generate.py                # openapi.json -> modules
    python ansible/generator/generate.py --export-spec  # backend app -> openapi.json, then modules
    python ansible/generator/generate.py --check        # fail if anything is stale (CI)

``--export-spec`` (and ``--check --export-spec``) import the FastAPI app, so
they need the backend's dependencies installed (``pip install ./backend``).

Inputs: ``ansible/openapi.json`` (a snapshot of the API's schema) and
``ansible/generator/resources.yml`` (which operations form which module).
Outputs: ``plugins/modules/*.py``, ``meta/runtime.yml`` and the module table
in the collection README. Generated files start with a DO NOT EDIT header.
"""
