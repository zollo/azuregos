def check_coverage(spec: Spec, config: dict, mods: list[dict]) -> list[str]:
    used = {op for m in mods for op in m["operations"]}
    ignored = set(config.get("ignore", {}))
    problems = []
    for op in spec.all_operations():
        if op not in used and op not in ignored:
            problems.append(
                f"{op} isn't covered by a module: add it to a module in resources.yml, "
                "or to `ignore` with a reason"
            )
    for op in sorted(ignored - set(spec.all_operations())):
        problems.append(f"ignored operation {op} no longer exists; remove it from resources.yml")
    return problems


def generate(spec_doc: dict) -> dict[Path, str]:
    config = yaml.safe_load(CONFIG_PATH.read_text())
    spec = Spec(spec_doc)
    mods = [build_module(name, cfg, spec) for name, cfg in sorted(config["modules"].items())]
    problems = check_coverage(spec, config, mods)
    if problems:
        raise GeneratorError("\n".join(problems))
    files = {MODULES_DIR / f"{m['name']}.py": render_module(m) for m in mods}
    files.update(render_roles(config, {m["name"]: m for m in mods}))
    files[COLLECTION / "meta" / "runtime.yml"] = render_runtime(mods)
    readme_path = COLLECTION / "README.md"
    readme = readme_path.read_text()
    start, end = readme.index(README_START), readme.index(README_END)
    files[readme_path] = (
        readme[: start + len(README_START)] + "\n" + render_table(mods) + "\n" + readme[end:]
    )
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--export-spec", action="store_true",
                        help="rebuild ansible/openapi.json from the backend app first")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 if any generated file is stale")
    args = parser.parse_args(argv)

    stale: list[str] = []
    if args.export_spec:
        spec_text = dump_spec(export_spec())
        if args.check:
            if not SPEC_PATH.exists() or SPEC_PATH.read_text() != spec_text:
                stale.append(str(SPEC_PATH.relative_to(REPO)))
        else:
            SPEC_PATH.write_text(spec_text)
        spec_doc = json.loads(spec_text)
    else:
        spec_doc = json.loads(SPEC_PATH.read_text())

    try:
        files = generate(spec_doc)
    except GeneratorError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    expected_modules = {p for p in files if p.parent == MODULES_DIR}
    leftovers = [p for p in MODULES_DIR.glob("*.py")
                 if p not in expected_modules and p.name != "__init__.py"
                 and HEADER.splitlines()[0] in p.read_text()]
    if args.check:
        stale += [str(p.relative_to(REPO)) for p, text in files.items()
                  if not p.exists() or p.read_text() != text]
        stale += [str(p.relative_to(REPO)) + " (no longer generated)" for p in leftovers]
        if stale:
            print("The Ansible collection is out of date with the API:", file=sys.stderr)
            for path in stale:
                print(f"  {path}", file=sys.stderr)
            print("Run: python ansible/generator/generate.py --export-spec", file=sys.stderr)
            return 1
        print(f"Collection is up to date ({len(expected_modules)} modules).")
        return 0

    MODULES_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"wrote {path.relative_to(REPO)}")
    for path in leftovers:
        path.unlink()
        print(f"removed {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
