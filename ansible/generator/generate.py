class GeneratorError(Exception):
    pass


# ── Spec helpers ──────────────────────────────────────────────────────────


def export_spec() -> dict:
    """Build the OpenAPI document from the FastAPI app (needs backend deps)."""
    sys.path.insert(0, str(REPO / "backend"))
    from app.main import app  # noqa: PLC0415

    spec = app.openapi()
    # The version is the build's (AZUREGOS_VERSION); keep the snapshot stable.
    spec["info"]["version"] = "snapshot"
    return spec


def dump_spec(spec: dict) -> str:
    return json.dumps(spec, indent=2, sort_keys=True) + "\n"


class Spec:
    def __init__(self, doc: dict):
        self.doc = doc

    def resolve(self, schema: dict, seen: tuple = ()) -> dict:
        """Inline every $ref (the schemas here aren't recursive)."""
        if not isinstance(schema, dict):
            return schema
        if "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[-1]
            if name in seen:
                raise GeneratorError(f"recursive schema {name}")
            target = copy.deepcopy(self.doc["components"]["schemas"][name])
            extra = {k: v for k, v in schema.items() if k != "$ref"}
            target.update(extra)  # sibling description/default override the target's
            return self.resolve(target, seen + (name,))
        out = {}
        for key, value in schema.items():
            if isinstance(value, dict):
                out[key] = self.resolve(value, seen)
            elif isinstance(value, list):
                out[key] = [self.resolve(v, seen) for v in value]
            else:
                out[key] = value
        return out

    def operation(self, ref: str) -> tuple[str, str, dict]:
        method, path = ref.split(" ", 1)
        op = self.doc["paths"].get(path, {}).get(method.lower())
        if op is None:
            raise GeneratorError(f"{ref} is not in the OpenAPI spec")
        return method.lower(), path, op

    def request_schema(self, op: dict) -> dict:
        content = op.get("requestBody", {}).get("content", {})
        schema = content.get("application/json", {}).get("schema")
        if schema is None:
            raise GeneratorError(f"{op.get('operationId')} has no JSON request body")
        return self.resolve(schema)

    def response_schema(self, op: dict) -> dict | None:
        for code in ("200", "201"):
            content = op.get("responses", {}).get(code, {}).get("content", {})
            schema = content.get("application/json", {}).get("schema")
            if schema is not None:
                return self.resolve(schema)
        return None

    def query_params(self, op: dict) -> list[dict]:
        return [self.resolve(p) for p in op.get("parameters", []) if p.get("in") == "query"]

    def all_operations(self) -> list[str]:
        return [
            f"{method.upper()} {path}"
            for path, item in self.doc["paths"].items()
            for method in item
            if method in HTTP_METHODS
        ]


# ── Schema -> argument spec / documentation ──────────────────────────────


def split_nullable(schema: dict) -> tuple[dict, bool]:
    """``anyOf: [X, null]`` -> (X with the outer description/default, True)."""
    if "anyOf" in schema:
        non_null = [s for s in schema["anyOf"] if s.get("type") != "null"]
        nullable = len(non_null) < len(schema["anyOf"])
        if len(non_null) == 1:
            inner = dict(non_null[0])
            for key in ("description", "title", "default"):
                if key in schema:
                    inner.setdefault(key, schema[key])
            return inner, nullable
        return {"description": schema.get("description", schema.get("title", ""))}, nullable
    return schema, False


ANSIBLE_TYPES = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
    "array": "list",
    "object": "dict",
}


def describe(schema: dict) -> str:
    text = schema.get("description") or schema.get("title") or ""
    return " ".join(text.split())


def constraint_notes(schema: dict) -> list[str]:
    notes = []
    if "minLength" in schema and "maxLength" in schema:
        notes.append(f"{schema['minLength']} to {schema['maxLength']} characters.")
    elif "maxLength" in schema:
        notes.append(f"At most {schema['maxLength']} characters.")
    elif "minLength" in schema and schema["minLength"] > 0:
        notes.append(f"At least {schema['minLength']} characters.")
    if "pattern" in schema:
        notes.append(f"Must match C({schema['pattern']}).")
    fmt = schema.get("format")
    if fmt == "uuid":
        notes.append("A UUID.")
    elif fmt == "email":
        notes.append("An email address.")
    return notes


def option_from_schema(schema: dict, *, top_level: bool, required: bool = False):
    """Return (argument_spec entry, DOCUMENTATION entry) for one schema property.

    Top-level options get no Ansible default: an unset option means "leave it
    as it is" on update, and the API applies its own default on create (the
    docs say what it is). Suboptions of list items do get the API's defaults,
    because a list is always sent whole.
    """
    inner, nullable = split_nullable(schema)
    kind = inner.get("type")
    if "enum" in inner:
        kind = inner.get("type", "string")
    ans_type = ANSIBLE_TYPES.get(kind, "raw")
    arg: dict = {"type": ans_type}
    doc: dict = {"description": [], "type": ans_type}

    text = describe(schema) or describe(inner)
    if text:
        doc["description"].append(text)
    doc["description"].extend(constraint_notes(inner))

    if "enum" in inner:
        arg["choices"] = list(inner["enum"])
        doc["choices"] = list(inner["enum"])

    if ans_type == "list":
        items, _ = split_nullable(inner.get("items", {}))
        item_type = ANSIBLE_TYPES.get(items.get("type"), "raw")
        if "enum" in items:
            item_type = "str"
        arg["elements"] = item_type
        doc["elements"] = item_type
        if item_type == "dict" and "properties" in items:
            arg["options"], doc["suboptions"] = suboptions(items)
        notes = constraint_notes(items)
        if notes:
            doc["description"].append("Each item: " + " ".join(notes))
    elif ans_type == "dict" and "properties" in inner:
        arg["options"], doc["suboptions"] = suboptions(inner)

    default = schema.get("default", inner.get("default"))
    if top_level:
        if default not in (None, [], {}, ""):
            doc["description"].append(f"The API uses C({json.dumps(default)}) when creating.")
        elif default == "" and ans_type == "str":
            doc["description"].append("The API uses an empty string when creating.")
    elif default is not None:
        arg["default"] = default
        doc["default"] = default
    if required:
        arg["required"] = True
        doc["required"] = True
    if not doc["description"]:
        doc["description"] = ["See the Azuregos API documentation."]
    return arg, doc, nullable


def suboptions(schema: dict):
    args, docs = {}, {}
    required = set(schema.get("required", []))
    for name, prop in schema["properties"].items():
        arg, doc, _ = option_from_schema(prop, top_level=False, required=name in required)
        args[name], docs[name] = arg, doc
    return args, docs


def return_docs(schema: dict | None, description: str, *, as_list: bool = False) -> dict:
    """RETURN entry for a response schema."""
    entry: dict = {"description": description, "returned": "success"}
    if schema is None:
        entry["type"] = "raw"
        return entry
    inner, _ = split_nullable(schema)
    if as_list or inner.get("type") == "array":
        items, _ = split_nullable(inner.get("items", {}))
        entry["type"] = "list"
        entry["elements"] = "dict"
        if "properties" in items:
            entry["contains"] = return_contains(items)
        return entry
    entry["type"] = "dict"
    if "properties" in inner:
        entry["contains"] = return_contains(inner)
    return entry


def return_contains(schema: dict) -> dict:
    out = {}
    for name, prop in schema["properties"].items():
        inner, _ = split_nullable(prop)
        kind = ANSIBLE_TYPES.get(inner.get("type"), "raw")
        if "enum" in inner:
            kind = "str"
        doc: dict = {
            "description": describe(prop) or describe(inner) or name.replace("_", " "),
            "type": kind,
            "returned": "always",
        }
        if kind == "list":
            items, _ = split_nullable(inner.get("items", {}))
            doc["elements"] = ANSIBLE_TYPES.get(items.get("type"), "raw")
            if "properties" in items:
                doc["contains"] = return_contains(items)
        elif kind == "dict" and "properties" in inner:
            doc["contains"] = return_contains(inner)
        out[name] = doc
    return out


# ── Module assembly ───────────────────────────────────────────────────────


def state_option(noun: str):
    arg = {"type": "str", "choices": ["present", "absent"], "default": "present"}
    doc = {
        "description": [f"Whether the {noun} should exist."],
        "type": "str",
        "choices": ["present", "absent"],
        "default": "present",
    }
    return arg, doc


def secret_update_option(name: str, noun: str):
    choices = ["always", "on_create"]
    arg = {"type": "str", "choices": choices, "default": "on_create", "no_log": False}
    doc = {
        "description": [
            f"C(on_create) sends O({name}) only when the {noun} is created, so the task "
            "stays idempotent (the API never returns it).",
            "C(always) sends it on every run and always reports a change.",
        ],
        "type": "str",
        "choices": choices,
        "default": "on_create",
    }
    return arg, doc


def op_ref(method: str, path: str) -> dict:
    return {"method": method, "path": path}


def build_module(name: str, cfg: dict, spec: Spec) -> dict:
    kind = cfg["kind"]
    noun = cfg.get("noun", name.replace("_", " "))
    options_arg: dict = {}
    options_doc: dict = {}
    resource: dict = {"kind": kind, "noun": noun, "return_key": cfg["return_key"]}
    write_only = cfg.get("write_only", [])
    operations: list[str] = []

    def add_props(schema: dict, nullable_from: dict | None):
        for prop_name, prop in schema["properties"].items():
            if prop_name in options_arg:
                continue
            arg, doc, nullable = option_from_schema(prop, top_level=True)
            if nullable_from is not None:
                _, nullable = split_nullable(nullable_from["properties"].get(prop_name, {}))
            else:
                nullable = False
            if prop_name in write_only:
                arg["no_log"] = True
            if nullable and arg["type"] == "str" and prop_name not in write_only:
                doc["description"].append("Set to an empty string to clear it (null).")
                resource.setdefault("nullable", []).append(prop_name)
            options_arg[prop_name] = arg
            options_doc[prop_name] = doc

    if kind == "collection":
        ops = {}
        for op_name in ("list", "create", "update", "delete"):
            method, path, op = spec.operation(cfg[op_name])
            operations.append(cfg[op_name])
            ops[op_name] = (method, path, op)
            resource[op_name] = op_ref(method, path)
        create_schema = spec.request_schema(ops["create"][2])
        update_schema = spec.request_schema(ops["update"][2])
        resource["create"]["schema"] = slim_schema(create_schema)
        resource["update"]["schema"] = slim_schema(update_schema)
        resource["identity"] = cfg["identity"]
        resource["id_param"] = cfg["id_param"]
        arg, doc = state_option(noun)
        options_arg["state"], options_doc["state"] = arg, doc
        options_arg["id"] = {"type": "str"}
        options_doc["id"] = {
            "description": [
                f"ID of an existing {noun}. Without it the {noun} is found by "
                f"O({cfg['identity']}); with it O({cfg['identity']}) can be changed.",
            ],
            "type": "str",
        }
        add_props(create_schema, create_schema)
        add_props(update_schema, None)
        if cfg["identity"] not in update_schema["properties"]:
            options_doc[cfg["identity"]]["description"].append(
                f"Identifies the {noun}; it can't be changed after creation."
            )
        item_schema = spec.response_schema(ops["update"][2])
        returns = {cfg["return_key"]: return_docs(
            item_schema, f"The {noun} as the API returns it (empty after state=absent)."
        )}
    elif kind == "singleton":
        ops = {}
        for op_name in ("read", "write", "delete"):
            method, path, op = spec.operation(cfg[op_name])
            operations.append(cfg[op_name])
            ops[op_name] = (method, path, op)
            resource[op_name] = op_ref(method, path)
        write_schema = spec.request_schema(ops["write"][2])
        resource["write"]["schema"] = slim_schema(write_schema)
        if cfg.get("read_key"):
            resource["read_key"] = cfg["read_key"]
        arg, doc = state_option(noun)
        options_arg["state"], options_doc["state"] = arg, doc
        add_props(write_schema, write_schema)
        for prop_name in write_schema.get("required", []):
            options_doc[prop_name]["description"].append("Required when O(state=present).")
        returns = {cfg["return_key"]: return_docs(
            spec.response_schema(ops["read"][2]), f"The {noun} status after the task."
        )}
    elif kind == "action":
        method, path, op = spec.operation(cfg["call"])
        operations.append(cfg["call"])
        call_schema = spec.request_schema(op)
        resource["call"] = op_ref(method, path)
        resource["call"]["schema"] = slim_schema(call_schema)
        add_props(call_schema, call_schema)
        for prop_name in call_schema.get("required", []):
            options_arg[prop_name]["required"] = True
            options_doc[prop_name]["required"] = True
        returns = {cfg["return_key"]: return_docs(
            spec.response_schema(op), "What the API reported."
        )}
    elif kind == "info":
        method, path, op = spec.operation(cfg["read"])
        operations.append(cfg["read"])
        resource["read"] = op_ref(method, path)
        response = spec.response_schema(op)
        query = []
        for param in spec.query_params(op):
            arg, doc, _ = option_from_schema(
                dict(param.get("schema", {}), description=param.get("description")
                     or param.get("schema", {}).get("title", "")),
                top_level=True,
            )
            if param.get("required"):
                arg["required"] = True
                doc["required"] = True
            options_arg[param["name"]], options_doc[param["name"]] = arg, doc
            query.append(param["name"])
        if query:
            resource["query"] = query
        filters = cfg.get("filters", [])
        if filters:
            if not response or response.get("type") != "array":
                raise GeneratorError(f"{name}: filters need a list response")
            item = split_nullable(response["items"])[0]
            for field in filters:
                if field not in item.get("properties", {}):
                    raise GeneratorError(f"{name}: {field} isn't a field of the response")
                arg, doc, _ = option_from_schema(item["properties"][field], top_level=False)
                arg.pop("default", None)
                doc.pop("default", None)
                doc["description"] = [f"Only return items whose C({field}) is this value."] + [
                    d for d in doc["description"] if not d.startswith("The API uses")
                ]
                options_arg[field], options_doc[field] = arg, doc
            resource["filters"] = filters
        returns = {cfg["return_key"]: return_docs(
            response, describe(op) or op.get("summary", "The API's response.")
        )}
    else:
        raise GeneratorError(f"{name}: unknown kind {kind}")

    clash = sorted(set(options_arg) & CONNECTION_OPTIONS)
    if clash:
        raise GeneratorError(
            f"{name}: API field(s) {', '.join(clash)} clash with connection options"
        )
    for field in write_only:
        if field not in options_arg:
            raise GeneratorError(f"{name}: write_only field {field} isn't an option")
        resource.setdefault("write_only", []).append(field)
        if kind in ("collection", "singleton"):
            key = f"update_{field}"
            options_arg[key], options_doc[key] = secret_update_option(field, noun)
    for key in ("unordered", "normalize"):
        if cfg.get(key):
            resource[key] = cfg[key]

    description = [" ".join(cfg["description"].split())]
    if cfg.get("requires"):
        description.append(f"Requires {cfg['requires']}")
    doc = {
        "module": name,
        "short_description": cfg["short_description"],
        "description": description,
        "author": ["Azuregos contributors (@zollo)"],
        "extends_documentation_fragment": [f"{FQCN}.connection"],
        "notes": ["Generated from the Azuregos OpenAPI spec. API operations: "
                  + ", ".join(f"C({o})" for o in operations) + "."],
        "options": dict(sorted(options_doc.items())),
    }
    attributes = {
        "check_mode": {"support": "full"},
        "diff_mode": {"support": "full" if kind in ("collection", "singleton") else "none"},
    }
    if kind in ("info", "action"):
        doc["notes"].append("This module never changes anything and always runs in check mode.")
    doc["extends_documentation_fragment"].append(f"{FQCN}.attributes")
    doc["attributes"] = attributes
    return {
        "name": name,
        "kind": kind,
        "doc": doc,
        "examples": cfg.get("examples", "").strip("\n") + "\n",
        "returns": returns,
        "options": dict(sorted(options_arg.items())),
        "resource": resource,
        "operations": operations,
        "short_description": cfg["short_description"],
    }


SCHEMA_SCALARS = {"type", "required", "enum", "minLength", "maxLength", "pattern", "format"}


def slim_schema(schema):
    """Keep only what the runtime validator reads (smaller generated modules)."""
    if isinstance(schema, list):
        return [slim_schema(s) for s in schema]
    if not isinstance(schema, dict):
        return schema
    out = {}
    for key, value in schema.items():
        if key == "properties":
            out[key] = {name: slim_schema(prop) for name, prop in value.items()}
        elif key in ("items", "anyOf"):
            out[key] = slim_schema(value)
        elif key in SCHEMA_SCALARS:
            out[key] = value
    return out


def yaml_block(data) -> str:
    class Dumper(yaml.SafeDumper):
        pass

    def str_presenter(dumper, value):
        style = "|" if "\n" in value else ('"' if "{{" in value else None)
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)

    Dumper.add_representer(str, str_presenter)
    return yaml.dump(data, Dumper=Dumper, sort_keys=False, width=88, allow_unicode=True)


def py_literal(value, level: int = 0) -> str:
    """A PEP 8 (hanging-indent) Python literal for JSON-like data, keys sorted."""
    pad, inner = " " * (4 * level), " " * (4 * (level + 1))
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [f"{inner}{k!r}: {py_literal(v, level + 1)}," for k, v in sorted(value.items())]
        return "{\n" + "\n".join(items) + "\n" + pad + "}"
    if isinstance(value, list):
        flat = "[" + ", ".join(py_literal(v, level + 1) for v in value) + "]"
        if "\n" not in flat and len(flat) + len(inner) < 90:
            return flat
        return "[\n" + "\n".join(f"{inner}{py_literal(v, level + 1)}," for v in value) + \
            "\n" + pad + "]"
    return repr(value)


def render_module(mod: dict) -> str:
    options = py_literal(mod["options"])
    resource = py_literal(mod["resource"])
    return f'''#!/usr/bin/python
# -*- coding: utf-8 -*-
{HEADER}
# GNU General Public License v3.0+ (see https://www.gnu.org/licenses/gpl-3.0.txt)

from __future__ import absolute_import, division, print_function

__metaclass__ = type

DOCUMENTATION = r"""
{yaml_block(mod["doc"]).rstrip()}
"""

EXAMPLES = r"""
{mod["examples"].rstrip()}
"""

RETURN = r"""
{yaml_block(mod["returns"]).rstrip()}
"""

from ansible_collections.zollo.azuregos.plugins.module_utils.azuregos import run_module

OPTIONS = {options}

RESOURCE = {resource}


def main():
    run_module(OPTIONS, RESOURCE)


if __name__ == "__main__":
    main()
'''


def render_runtime(mods: list[dict]) -> str:
    data = {
        "requires_ansible": ">=2.15.0",
        "action_groups": {"all": [m["name"] for m in mods]},
    }
    return HEADER + "\n---\n" + yaml.safe_dump(data, sort_keys=False)


def render_table(mods: list[dict]) -> str:
    rows = ["| Module | What it does | API operations |", "|---|---|---|"]
    for m in mods:
        ops = "<br>".join(f"`{o}`" for o in m["operations"])
        rows.append(f"| `{FQCN}.{m['name']}` | {m['short_description']} | {ops} |")
    return "\n".join(rows)


