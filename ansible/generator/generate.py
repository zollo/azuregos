def role_doc_option(doc: dict) -> dict:
    out = {"type": doc["type"], "description": doc["description"]}
    for key in ("choices", "default", "elements", "required"):
        if key in doc:
            out[key] = doc[key]
    if "suboptions" in doc:
        out["options"] = {k: role_doc_option(v) for k, v in doc["suboptions"].items()}
    return out


def ref_doc(ref_name: str, ref: dict, mods: dict) -> dict:
    target = mods[ref["from"]]
    identity = target["resource"]["identity"]
    if ref.get("list"):
        return {
            "type": "list", "elements": "str",
            "description": [f"{identity.capitalize()}s of {target['resource']['noun']}s; the role "
                            f"looks up their IDs and sets {ref['option']}."],
        }
    return {
        "type": "str",
        "description": [f"{identity.capitalize()} of the {target['resource']['noun']}; the role "
                        f"looks up its ID and sets {ref['option']}. An empty string clears it."],
    }


def ref_expr(ref_name: str, ref: dict, src: str) -> str:
    ids = f"azuregos__ids.{ref['from']}"
    if ref.get("list"):
        value = (f"{ids} | dict2items | selectattr('key', 'in', {src}.{ref_name}) "
                 "| map(attribute='value') | list")
    else:
        value = (f"(({ids}[{src}.{ref_name}] | default('{ZERO_UUID}')) "
                 f"if {src}.{ref_name} else '')")
    return (f"{{{{ ({value}) if {src}.{ref_name} is defined "
            f"else ({src}.{ref['option']} | default(omit)) }}}}")


def render_role_tasks(entry: dict, mods: dict, referenced: set) -> str:
    mod = mods[entry["module"]]
    res = mod["resource"]
    var = entry["var"]
    refs = entry.get("references", {})
    singleton = mod["kind"] == "singleton"
    src = var if singleton else "item"
    params = {}
    for opt in mod["options"]:
        params[opt] = f"{{{{ {src}.{opt} | default(omit) }}}}"
    for ref_name, ref in refs.items():
        params[ref["option"]] = ref_expr(ref_name, ref, src)
    tasks = []
    for ref_name, ref in refs.items():
        target = mods[ref["from"]]
        pick = f"{var} | selectattr('{ref_name}', 'defined') | map(attribute='{ref_name}')"
        pick += " | flatten" if ref.get("list") else ""
        tasks.append({
            "name": f"Check that every {ref_name} in {var} exists",
            "ansible.builtin.assert": {
                "that": "azuregos__missing | length == 0",
                "fail_msg": f"Unknown {target['resource']['noun']}: "
                            "{{ azuregos__missing | join(', ') }}",
                "quiet": True,
            },
            "vars": {"azuregos__missing": f"{{{{ {pick} | select "
                                          f"| reject('in', azuregos__ids.{ref['from']}) "
                                          "| list }}"},
            "when": "not ansible_check_mode",
        })
    task = {"name": f"Azuregos {res['noun']}" if singleton else
            f"Azuregos {res['noun']} {{{{ item.{res['identity']} | default(item.id) }}}}"}
    task[f"{FQCN}.{entry['module']}"] = params
    if singleton:
        task["when"] = f"{var} is defined and {var} is mapping"
    else:
        task["loop"] = f"{{{{ {var} }}}}"
        task["loop_control"] = {"label": f"{{{{ item.{res['identity']} | default(item.id) }}}}"}
    tasks.append(task)
    if entry["module"] in referenced:
        info = mods[f"{entry['module']}_info"]
        tasks.append({
            "name": f"Look up {res['noun']} IDs",
            f"{FQCN}.{info['name']}": {},
            "register": f"azuregos__{entry['module']}_info",
            "check_mode": False,
        })
        lookup = (f"{{{{ azuregos__ids | combine({{'{entry['module']}': "
                  f"azuregos__{entry['module']}_info.{info['resource']['return_key']} "
                  f"| items2dict(key_name='{res['identity']}', value_name='id')}}) }}}}")
        tasks.append({"name": f"Remember {res['noun']} IDs",
                      "ansible.builtin.set_fact": {"azuregos__ids": lookup}})
    return HEADER + "\n---\n" + yaml_block(tasks)


def render_roles(config: dict, mods: dict) -> dict:
    role_cfg = config["role"]
    entries = role_cfg["resources"]
    referenced = {ref["from"] for e in entries for ref in e.get("references", {}).values()}
    files = {}
    configure = COLLECTION / "roles" / "configure"
    options = dict(ROLE_CONNECTION_OPTIONS)
    export = []
    for entry in entries:
        mod = mods[entry["module"]]
        sub = {k: role_doc_option(v) for k, v in mod["doc"]["options"].items()}
        for ref_name, ref in entry.get("references", {}).items():
            sub[ref_name] = ref_doc(ref_name, ref, mods)
        desc = mod["doc"]["description"][0]
        if mod["kind"] == "singleton":
            options[entry["var"]] = {
                "type": "dict", "options": sub,
                "description": [f"Options of {FQCN}.{entry['module']}: {desc}",
                                "Left unset, the role doesn't touch it."],
            }
        else:
            options[entry["var"]] = {
                "type": "list", "elements": "dict", "default": [], "options": sub,
                "description": [f"Each item is the options of {FQCN}.{entry['module']}: {desc}"],
            }
        files[configure / "tasks" / f"{entry['module']}.yml"] = render_role_tasks(
            entry, mods, referenced)
        res = mod["resource"]
        write_only = set(res.get("write_only", []))
        if mod["kind"] == "singleton":
            fields = [f for f in res["write"]["schema"]["properties"] if f not in write_only]
            export.append({"var": entry["var"], "info": f"{entry['module']}_info",
                           "return_key": res["return_key"], "read_key": res.get("read_key"),
                           "fields": fields})
            continue
        fields = list(dict.fromkeys(list(res["create"]["schema"]["properties"])
                                    + list(res["update"]["schema"]["properties"])))
        fields = [f for f in fields if f not in write_only]
        refs = {ref["option"]: {"name": ref_name, "from": ref["from"],
                                "list": bool(ref.get("list"))}
                for ref_name, ref in entry.get("references", {}).items()}
        export.append({"var": entry["var"], "info": f"{entry['module']}_info",
                       "return_key": mods[f"{entry['module']}_info"]["resource"]["return_key"],
                       "identity": res["identity"], "fields": fields, "references": refs})
    files[configure / "meta" / "argument_specs.yml"] = HEADER + "\n---\n" + yaml_block({
        "argument_specs": {"main": {
            "short_description": "Apply an Azuregos configuration from variables",
            "description": [
                "Waits for the API, signs in once, then applies "
                + ", ".join(e["var"] for e in entries) + " in that order.",
                "Each variable's items take the options of the matching module, checked "
                "against the API's schema before anything is sent.",
            ],
            "options": options,
        }},
    })
    files[configure / "tasks" / "resources.yml"] = HEADER + "\n---\n" + yaml_block([
        {"name": f"Apply {e['var']}",
         "ansible.builtin.include_tasks": f"{e['module']}.yml"}
        for e in entries
    ])
    files[COLLECTION / "roles" / "export" / "vars" / "main.yml"] = (
        HEADER + "\n---\n" + yaml_block({"azuregos__export": export}))
    return files


